-- Execute after 001_foundation.sql with a grant administrator.
-- No users are created or assigned automatically. Review existing role inheritance.
USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS HEALTH_ANALYTICS_WH
    WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;
CREATE WAREHOUSE IF NOT EXISTS HEALTH_BIOSTATISTICS_WH
    WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE;

-- Data Engineering owns the published schemas and all shared source objects.
-- Team-created objects belong in separate managed-access workspaces.
CREATE SCHEMA IF NOT EXISTS HEALTH_DATA_PROJECT.ANALYTICS_WORKSPACE WITH MANAGED ACCESS;
CREATE SCHEMA IF NOT EXISTS HEALTH_DATA_PROJECT.BIOSTATISTICS_WORKSPACE WITH MANAGED ACCESS;

USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS ANALYTICS_ROLE;
CREATE ROLE IF NOT EXISTS BIOSTATISTICS_ROLE;

GRANT USAGE ON DATABASE HEALTH_DATA_PROJECT TO ROLE ANALYTICS_ROLE;
GRANT USAGE ON SCHEMA HEALTH_DATA_PROJECT.ANALYTICS TO ROLE ANALYTICS_ROLE;
GRANT SELECT ON ALL VIEWS IN SCHEMA HEALTH_DATA_PROJECT.ANALYTICS TO ROLE ANALYTICS_ROLE;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA HEALTH_DATA_PROJECT.ANALYTICS TO ROLE ANALYTICS_ROLE;
GRANT USAGE ON WAREHOUSE HEALTH_ANALYTICS_WH TO ROLE ANALYTICS_ROLE;

GRANT USAGE ON DATABASE HEALTH_DATA_PROJECT TO ROLE BIOSTATISTICS_ROLE;
GRANT USAGE ON SCHEMA HEALTH_DATA_PROJECT.BIOSTATISTICS TO ROLE BIOSTATISTICS_ROLE;
GRANT SELECT ON ALL VIEWS IN SCHEMA HEALTH_DATA_PROJECT.BIOSTATISTICS TO ROLE BIOSTATISTICS_ROLE;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA HEALTH_DATA_PROJECT.BIOSTATISTICS TO ROLE BIOSTATISTICS_ROLE;
GRANT USAGE ON WAREHOUSE HEALTH_BIOSTATISTICS_WH TO ROLE BIOSTATISTICS_ROLE;

GRANT USAGE, CREATE TABLE, CREATE VIEW
    ON SCHEMA HEALTH_DATA_PROJECT.ANALYTICS_WORKSPACE TO ROLE ANALYTICS_ROLE;
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE
    ON ALL TABLES IN SCHEMA HEALTH_DATA_PROJECT.ANALYTICS_WORKSPACE TO ROLE ANALYTICS_ROLE;
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE
    ON FUTURE TABLES IN SCHEMA HEALTH_DATA_PROJECT.ANALYTICS_WORKSPACE TO ROLE ANALYTICS_ROLE;
GRANT SELECT ON ALL VIEWS IN SCHEMA HEALTH_DATA_PROJECT.ANALYTICS_WORKSPACE TO ROLE ANALYTICS_ROLE;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA HEALTH_DATA_PROJECT.ANALYTICS_WORKSPACE TO ROLE ANALYTICS_ROLE;

GRANT USAGE, CREATE TABLE, CREATE VIEW
    ON SCHEMA HEALTH_DATA_PROJECT.BIOSTATISTICS_WORKSPACE TO ROLE BIOSTATISTICS_ROLE;
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE
    ON ALL TABLES IN SCHEMA HEALTH_DATA_PROJECT.BIOSTATISTICS_WORKSPACE TO ROLE BIOSTATISTICS_ROLE;
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE
    ON FUTURE TABLES IN SCHEMA HEALTH_DATA_PROJECT.BIOSTATISTICS_WORKSPACE TO ROLE BIOSTATISTICS_ROLE;
GRANT SELECT ON ALL VIEWS IN SCHEMA HEALTH_DATA_PROJECT.BIOSTATISTICS_WORKSPACE TO ROLE BIOSTATISTICS_ROLE;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA HEALTH_DATA_PROJECT.BIOSTATISTICS_WORKSPACE TO ROLE BIOSTATISTICS_ROLE;

-- Administrators inherit reader access; readers do not inherit SYSADMIN.
GRANT ROLE ANALYTICS_ROLE TO ROLE SYSADMIN;
GRANT ROLE BIOSTATISTICS_ROLE TO ROLE SYSADMIN;

-- Published consumer schemas expose views only and remain read-only.
-- Workspaces allow derived tables/views and DML. Objects created with the team
-- role are owned by that role, allowing ALTER, DROP, and CREATE OR REPLACE.
-- Managed access reserves grant administration for the schema administrator.
-- Internal RAW/STAGING/VAULT/BUSINESS/MARTS/PUBLICATION_BUILD are not granted.
SHOW GRANTS TO ROLE ANALYTICS_ROLE;
SHOW FUTURE GRANTS TO ROLE ANALYTICS_ROLE;
SHOW GRANTS TO ROLE BIOSTATISTICS_ROLE;
SHOW FUTURE GRANTS TO ROLE BIOSTATISTICS_ROLE;

